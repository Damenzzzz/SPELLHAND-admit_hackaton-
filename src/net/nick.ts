const ADJ = ['Огненный', 'Ледяной', 'Грозовой', 'Тихий', 'Древний', 'Лунный', 'Звёздный', 'Теневой', 'Рунный', 'Юный'];
const NOUN = ['Маг', 'Чародей', 'Колдун', 'Мистик', 'Друид', 'Ведун', 'Заклинатель', 'Алхимик', 'Странник', 'Архивариус'];

/** Случайный ник без клавиатуры — игрок управляет только жестами. */
export function randomNick(): string {
  const pick = <T,>(a: T[]) => a[Math.floor(Math.random() * a.length)];
  return `${pick(ADJ)} ${pick(NOUN)} ${Math.floor(10 + Math.random() * 90)}`;
}
