import { localize } from '../../i18n';

/**
 * Особые механики противников — данные уровня. Правила живут в движке (src/game/traits.ts),
 * здесь только параметры баланса и тексты. Все времена — в мс игрового времени боя.
 */
export type EnemyTrait =
  | {
      /** Маг с прерываемой атакой: копит силу, ветер во время подготовки сбивает её и оглушает. */
      kind: 'channeler';
      /** Первая подготовка после начала боя. */
      firstMs: number;
      /** Пауза между подготовками (после удара или срыва). */
      everyMs: number;
      /** Длительность подготовки — окно для ветра. */
      channelMs: number;
      /** Усиленная атака: заклинание и множитель урона. */
      spell: 'lightning' | 'fireball';
      powerMul: number;
      /** Оглушение после срыва ветром. */
      stunMs: number;
    }
  | {
      /** Ледяная броня: режет входящий урон, огненный шар растапливает её на время. */
      kind: 'iceArmor';
      /** Доля урона, которую броня поглощает. */
      reduction: number;
      /** Сколько броня восстанавливается после попадания огнём. */
      meltMs: number;
    }
  | {
      /** Дуэлянт: заметный выпад, парирование которого открывает его для урона. */
      kind: 'duelist';
      firstMs: number;
      everyMs: number;
      /** Замах перед выпадом (предупреждение). */
      windupMs: number;
      /** Полёт выпада — медленнее обычного, чтобы успеть парировать. */
      travelMs: number;
      /** Урон выпада относительно обычного огненного шара. */
      powerMul: number;
      /** Уязвимость после парирования выпада и множитель входящего урона. */
      exposedMs: number;
      exposedMul: number;
      /** В стойке (не открыт) дуэлянт получает меньше урона. */
      guardMul: number;
    };

export type TraitKind = EnemyTrait['kind'];

